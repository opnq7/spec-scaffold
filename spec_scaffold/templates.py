"""Markdown templates used by the scaffolder.

Every template is a :class:`string.Template`, so ``$IDEA``, ``$SLUG`` and
``$DATE`` are substituted when a spec folder is generated.
"""

from string import Template

REQUIREMENTS = Template(
    """# Requirements — $IDEA

> Generated by spec-scaffold on $DATE. Keep this file about **what** and **why**;
> implementation detail belongs in `design.md`.

## Overview

Describe $IDEA in one paragraph: who has the problem, what they do today, and
why that is painful. Aim for three sentences.

## User Stories

- **US-1** — As a <role>, I want <capability>, so that <outcome>.
- **US-2** — As a <role>, I want <capability>, so that <outcome>.

## Acceptance Criteria

Write each criterion as a testable WHEN / THE SYSTEM SHALL pair.

- **AC-1** — WHEN <trigger>, THE SYSTEM SHALL <observable behaviour>.
- **AC-2** — WHEN <trigger>, THE SYSTEM SHALL <observable behaviour>.

## Out of Scope

- <thing this version deliberately does not do>

## Open Questions

- [ ] <question that blocks a decision>
"""
)

DESIGN = Template(
    """# Design — $IDEA

> How the system meets `requirements.md`. One `specs/$SLUG/` folder = one change.

## Overview

The chosen approach in two or three sentences, plus the one alternative that was
rejected and why.

## Architecture

```
+-------------+      +-------------+      +-------------+
|   input     | ---> |   $SLUG     | ---> |   output    |
+-------------+      +-------------+      +-------------+
```

- **Module layout** — `<package>/` holds the entry point, `<package>/core.py`
  holds the pure logic, `tests/` mirrors it.

## Data Model

| Name | Type | Notes |
| --- | --- | --- |
| `id` | string | stable slug, unique per record |

## Error Handling

- Bad input: fail fast with a message that names the offending value.
- Missing files: report the path, never the traceback.

## Testing

- Unit tests for the pure functions.
- One end-to-end test that runs the CLI against a temp directory.
"""
)

TASKS = Template(
    """# Tasks — $IDEA

> Ordered, independently shippable steps. Tick a box only when the tests for it
> exist **and** pass.

## Phase 1 — Skeleton

- [ ] Create package layout and `pyproject.toml`
- [ ] Add a smoke test that imports the package
- [ ] Wire up CI (`pytest` on push and pull request)

## Phase 2 — Core behaviour

- [ ] Implement the pure functions for $IDEA
- [ ] Cover them with unit tests
- [ ] Expose them through the CLI

## Phase 3 — Polish

- [ ] Write the README with a real usage transcript
- [ ] Handle the obvious error cases ($IDEA with empty input, missing files)
- [ ] Tag `v0.1.0`
"""
)

#: File name -> template, in the order files are written.
FILES = {
    "requirements.md": REQUIREMENTS,
    "design.md": DESIGN,
    "tasks.md": TASKS,
}
